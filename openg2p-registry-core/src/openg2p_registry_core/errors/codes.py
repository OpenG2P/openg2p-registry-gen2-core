    # Partner Errors
    PARTNER_NOT_REGISTERED = ("PARTNER_NOT_REGISTERED", "REGP-ERR-001")
    DATA_MODEL_NOT_FOUND = ("DATA_MODEL_NOT_FOUND", "REGP-ERR-002")

