    REGISTER_DATA_NOT_FOUND = ("REGISTER_DATA_NOT_FOUND", "REG-ERR-002")
    CHANGE_LOG_NOT_FOUND = ("CHANGE_LOG_NOT_FOUND", "REG-ERR-003")
